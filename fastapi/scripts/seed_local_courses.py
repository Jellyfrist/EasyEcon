def get_or_create(db, model, lookup, **values):
    obj = db.query(model).filter_by(**lookup).first()
    if obj is None:
        obj = model(**lookup, **values)
        db.add(obj)
        db.flush()
    return obj


def seed():
    now = datetime.now(timezone.utc).replace(tzinfo=None)
    with SessionLocal() as db:
        teacher = db.query(User).filter_by(username='teacher.local', role='teacher').first()
        if teacher is None:
            raise SystemExit('Missing teacher.local; start the localhost backend first.')
        for slug, title, description, topics in COURSES:
            course = get_or_create(db, Course, dict(teacher_id=teacher.id, title=title),
                                   description=f'[ข้อมูลตัวอย่าง localhost] {description}')
            exam_questions = []
            for topic_index, (topic_title, concepts, questions) in enumerate(topics):
                module = get_or_create(db, Module, dict(course_id=course.id, title=topic_title),
                                       order_index=topic_index)
                for index, ((term, explanation), (question, options, correct, reason)) in enumerate(zip(concepts, questions)):
                    tag = f'local-{slug}-{topic_index}-{index}'
                    html = (f'<h2>{escape(term)}</h2><p>{escape(explanation)}</p>'
                            f'<h3>ลองคิดก่อนตอบ</h3><p>{escape(question)}</p>'
                            '<p>อ่านแนวคิดให้เข้าใจ แล้วทำคำถามท้ายบทเพื่อตรวจความเข้าใจ</p>')
                    page = get_or_create(db, LearningPage, dict(module_id=module.id, title=term),
                        order_index=index, preview=explanation, topic_tag=tag,
                        template_type='blank', is_published=True, published_at=now,
                        created_by_user_id=teacher.id, last_edited_by_user_id=teacher.id,
                        content_blocks=[
                            {'id': f'{tag}-text', 'type': 'rich_text_section', 'data': {'title': term, 'html': html}},
                            {'id': f'{tag}-quiz', 'type': 'mini_quiz', 'data': {'title': 'ตรวจความเข้าใจ', 'questions': [
                                {'id': f'{tag}-q', 'text': question, 'options': options,
                                 'correct_index': correct, 'explanation': reason}]}}
                        ])
                    exam_questions.append(ExamQuestion(
                        id=f'{tag}-exam', type='multiple_choice', text=question,
                        options=options, correct_answer=options[correct], explanation=reason,
                        points=5, topic_tag=tag, linked_learning_page_id=page.id,
                        order_index=len(exam_questions)).model_dump())
            template = get_or_create(db, ExamTemplate,
                dict(course_id=course.id, title=f'แบบทดสอบ: {title}'),
                created_by_user_id=teacher.id, description='ข้อสอบตัวอย่างพร้อมคำอธิบายและลิงก์กลับไปทบทวนบทเรียน',
                exam_type='quiz', academic_year='2026', term='1', question_data=exam_questions,
                time_limit_minutes=15, passing_score_pct=60, show_correct_after=True,
                allow_review=True, is_published=True)
            get_or_create(db, ExamSession, dict(template_id=template.id, title=template.title),
                instructions='เลือกคำตอบที่ถูกต้อง ข้อสอบนี้เป็นข้อมูลตัวอย่างสำหรับทดสอบระบบ localhost',
                question_snapshot=copy.deepcopy(template.question_data), time_limit_minutes=15,
                max_attempts=10, is_active=True, launched_by_user_id=teacher.id)
            print(f'{course.id}: {title} — 2 modules, 4 lessons, 1 exam')
        db.commit()


if __name__ == '__main__':
    seed()
